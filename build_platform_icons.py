"""Render small, bundled platform marks; Pillow is only needed to rebuild assets."""
from pathlib import Path
from PIL import Image, ImageDraw

OUT = Path(__file__).resolve().parent / 'assets' / 'platforms'
OUT.mkdir(parents=True, exist_ok=True)
S = 4


def render(name, paint):
    image = Image.new('RGBA', (100*S, 100*S))
    draw = ImageDraw.Draw(image)
    class Pen:
        def ellipse(self, box, fill):
            draw.ellipse(tuple(v*S for v in box), fill=fill)
        def rect(self, box, fill, radius=0):
            draw.rounded_rectangle(tuple(v*S for v in box), radius=radius*S, fill=fill)
        def line(self, points, fill, width):
            draw.line([(x*S,y*S) for x,y in points], fill=fill, width=width*S, joint='curve')
        def polygon(self, points, fill):
            draw.polygon([(x*S,y*S) for x,y in points], fill=fill)
        def path(self, start, curves, fill):
            points=[start]
            p=start
            for a,b,c in curves:
                for i in range(1,41):
                    t=i/40; u=1-t
                    points.append((u**3*p[0]+3*u*u*t*a[0]+3*u*t*t*b[0]+t**3*c[0], u**3*p[1]+3*u*u*t*a[1]+3*u*t*t*b[1]+t**3*c[1]))
                p=c
            self.polygon(points,fill)
    paint(Pen())
    image.resize((28,28), Image.Resampling.LANCZOS).save(OUT / f'{name}.png')


